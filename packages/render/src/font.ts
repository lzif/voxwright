const GLYPHS = new Map<string, string[]>(
  Object.entries(G).map(([ch, rows]) => [ch, rows.split("|")]),
);

/** Whole-number scale for a nominal text size in pixels. */
export const textScale = (size: number): number => Math.max(1, Math.round(size / 9));

/** Width in pixels of `text` at `size`. */
export const textWidth = (text: string, size: number): number => text.length * 6 * textScale(size);

export interface TextOptions {
  size: number;
  color: readonly [number, number, number];
  /** Outline thickness in pixels; 0 for none. */
  stroke?: number;
  strokeColor?: readonly [number, number, number];
}

function plot(canvas: Canvas, x: number, y: number, rgb: readonly [number, number, number]): void {
  if (x < 0 || y < 0 || x >= canvas.width || y >= canvas.height) return;
  const i = (y * canvas.width + x) * 3;
  canvas.data[i] = rgb[0];
  canvas.data[i + 1] = rgb[1];
  canvas.data[i + 2] = rgb[2];
}

function glyphPass(
  canvas: Canvas,
  x: number,
  y: number,
  text: string,
  scale: number,
  rgb: readonly [number, number, number],
  grow: number,
): void {
  let cx = x;
  for (const ch of text) {
    const rows = GLYPHS.get(ch) ?? GLYPHS.get("?");
    if (rows) {
      rows.forEach((row, ry) => {
        for (let rx = 0; rx < row.length; rx++) {
          if (row[rx] !== "#") continue;
          for (let dy = -grow; dy < scale + grow; dy++) {
            for (let dx = -grow; dx < scale + grow; dx++)
              plot(canvas, cx + rx * scale + dx, y + ry * scale + dy, rgb);
          }
        }
      });
    }
    cx += 6 * scale;
  }
}

/** Draw `text` with its top-left at `(x, y)`. */
export function drawText(
  canvas: Canvas,
  x: number,
  y: number,
  text: string,
  options: TextOptions,
): void {
  const scale = textScale(options.size);
  if (options.stroke)
    glyphPass(canvas, x, y, text, scale, options.strokeColor ?? [0, 0, 0], options.stroke);
  glyphPass(canvas, x, y, text, scale, options.color, 0);
}
